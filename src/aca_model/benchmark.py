"""Benchmark-sized baseline model with frozen parameters.

Exports a compact, fully self-contained setup that exercises the full
18-regime DAG with `BENCHMARK_GRID_CONFIG` grids (tiny n_points per
continuous state). Use for ASV benchmarks and fast end-to-end
integration tests without requiring the aca-data pipeline.

The benchmark substitutes a 2-type `BenchmarkPrefType` for the
production 3-type `PrefType`, which saves ~33% of the compile +
execution volume over all 18 regimes.

Parameters (`fixed_params` + `params`) are a committed snapshot at
`src/aca_model/_benchmark_data/benchmark_params.pkl`, generated by
`scripts/regen_benchmark_params.py` against the current aca-data +
aca-slurm + aca-model code. Pref-type-indexed Series in `params`
are pre-truncated to two rows so the snapshot loads with no further
reshaping; regenerate after any change that affects `fixed_params`
shape (regime DAGs, aca-data outputs, key renames).

Initial conditions are drawn randomly per call — assets/aime/wage_res
from their grid ranges, discrete states from their categories, regimes
sampled from the five regimes active at `start_age=51`.
"""

from pathlib import Path
from typing import Any

import cloudpickle
import jax.numpy as jnp
import numpy as np
from jax import Array
from lcm import DiscreteGrid, ExecutionConfig, Model

from aca_model.agent.health import GoodHealth
from aca_model.agent.labor_market import IsMarried
from aca_model.agent.preferences import BenchmarkPrefType
from aca_model.baseline.health_insurance import HealthInsuranceState
from aca_model.baseline.model import create_model
from aca_model.baseline.regimes import ENTRY_REGIMES
from aca_model.config import BENCHMARK_GRID_CONFIG
from aca_model.consumption_dollars_grid import (
    compute_consumption_dollars_points,
    inject_consumption_dollars_points,
    inject_consumption_floor_schedule,
)

_PARAMS_FILE = (
    Path(__file__).resolve().parent / "_benchmark_data" / "benchmark_params.pkl"
)

# Arguments of the regime-transition laws declared in `Model(edges=...)`. The
# snapshot stores them under each source regime; pylcm reads an edge-declared
# callable's parameters under `params["edges"][source]`.
_EDGE_LAW_PARAMS = frozenset({"survival_probs", "prob_disabled_next"})

_N_BENCHMARK_PREF_TYPES = len(DiscreteGrid(BenchmarkPrefType).categories)

_DERIVED_CATEGORICALS = {
    "good_health": DiscreteGrid(GoodHealth),
    "is_married": DiscreteGrid(IsMarried),
    "his": DiscreteGrid(HealthInsuranceState),
    "target_his": DiscreteGrid(HealthInsuranceState),
    "pref_type": DiscreteGrid(BenchmarkPrefType),
}

# The five entry regimes (inelig + canwork). All have
# HealthWithDisability (3-state); four have lagged_labor_supply (tied
# does not — it's implied by the regime).


def create_benchmark_model(
    *,
    pref_type_grid: DiscreteGrid,
    execution_config: ExecutionConfig | None = None,
) -> Model:
    """Create the aca baseline with `BENCHMARK_GRID_CONFIG` and frozen fixed_params.

    The benchmark uses a 2-type `BenchmarkPrefType`. Grids describe economic
    outcomes; the execution policy selects devices and program widths.

    Args:
        pref_type_grid: Pref-type grid; pass `DiscreteGrid(BenchmarkPrefType)`.
        execution_config: Explicit hardware-local policy forwarded unchanged.
            None uses the smallest selected accelerator allocator limit as the
            device-memory budget; CPU construction remains unbudgeted.
    """
    fixed_params, wage_params, _ = get_benchmark_params(model=None)
    return create_model(
        grid_config=BENCHMARK_GRID_CONFIG,
        fixed_params=fixed_params,
        wage_params=wage_params,
        derived_categoricals=_DERIVED_CATEGORICALS,
        pref_type_grid=pref_type_grid,
        execution_config=execution_config,
    )


def get_benchmark_params(
    *, model: Model | None
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    """Load the frozen `(fixed_params, wage_params, params)` snapshot.

    `max_consumption_dollars` is popped out of `fixed_params` before
    return — it's a grid-construction input read by
    `inject_consumption_dollars_points`, not by any DAG function, so
    leaving it in `fixed_params` would trip pylcm's unknown-keys check.

    When `model` is provided, consumption_dollars gridpoints are injected
    into `params` for each regime that declares `consumption_dollars` as
    an `IrregSpacedGrid` with runtime-supplied points. Pass `model=None`
    to skip injection (e.g. when constructing the model with
    `fixed_params`).

    The regime-transition law arguments (`survival_probs`,
    `prob_disabled_next`) are returned under `fixed_params["edges"][source]`,
    where pylcm looks for the parameters of edge-declared callables.
    """
    with _PARAMS_FILE.open("rb") as fh:
        data = cloudpickle.load(fh)
    fixed_params = _move_law_params_to_edges(data["fixed_params"])
    wage_params = data["wage_params"]
    params = data["params"]
    max_consumption_dollars = float(fixed_params.pop("max_consumption_dollars"))
    if model is not None:
        params = inject_consumption_dollars_points(
            params=params,
            model=model,
            max_consumption_dollars=max_consumption_dollars,
        )
        params = inject_consumption_floor_schedule(params=params, model=model)
    return fixed_params, wage_params, params


def _move_law_params_to_edges(fixed_params: dict[str, Any]) -> dict[str, Any]:
    """Move each source regime's law arguments to `edges[source]`.

    Every other entry, including the regime's own function parameters, keeps
    its path.
    """
    regimes = {
        name: value
        for name, value in fixed_params.items()
        if isinstance(value, dict) and not _EDGE_LAW_PARAMS.isdisjoint(value)
    }
    edges = {
        name: {k: v for k, v in value.items() if k in _EDGE_LAW_PARAMS}
        for name, value in regimes.items()
    }
    return {
        **{
            name: (
                {k: v for k, v in value.items() if k not in _EDGE_LAW_PARAMS}
                if name in regimes
                else value
            )
            for name, value in fixed_params.items()
        },
        "edges": edges,
    }


def get_benchmark_consumption_dollars_points(*, n_points: int) -> tuple[float, ...]:
    """Compute construction-time consumption_dollars points from the snapshot.

    Same formula as the runtime injection (single floor, married floor,
    geomspace tail to `max_consumption_dollars`), evaluated on the frozen
    snapshot's `consumption_equiv_floor` / `exponent` /
    `max_consumption_dollars`. DC-EGM builds need the continuous-action
    grid at model construction, so the points are passed to
    `create_model(consumption_dollars_points=...)` instead of injected
    into params.
    """
    with _PARAMS_FILE.open("rb") as fh:
        data = cloudpickle.load(fh)
    points = compute_consumption_dollars_points(
        consumption_equiv_floor=jnp.asarray(data["params"]["consumption_equiv_floor"]),
        exponent=jnp.asarray(data["fixed_params"]["exponent"]),
        max_consumption_dollars=jnp.asarray(
            float(data["fixed_params"]["max_consumption_dollars"])
        ),
        n_points=n_points,
    )
    return tuple(float(p) for p in points)


def get_benchmark_initial_conditions(
    *, model: Model, n_subjects: int, seed: int
) -> dict[str, Array]:
    """Draw random feasible initial conditions across five age-51 regimes.

    Every subject gets a random regime from `ENTRY_REGIMES`; continuous
    states are drawn uniformly over the regime's grid range, discrete states
    uniformly over categories. States absent from a subject's regime are
    filled with 0 (pylcm ignores them for that regime).
    """
    rng = np.random.default_rng(seed)
    regime_ids = tuple(model.regime_names_to_ids[n] for n in ENTRY_REGIMES)
    regime = rng.choice(regime_ids, size=n_subjects).astype(np.int32)

    # Grid ranges come from any of the five regimes (shared structure).
    # Use to_jax() so the helper handles both LinSpacedGrid and
    # PiecewiseLinSpacedGrid (the latter has no `.start` / `.stop`).
    ref_regime = model.user_regimes[ENTRY_REGIMES[0]]
    grids = ref_regime.states
    # Every state read here is a plain `Grid`; `pension_wealth` (a
    # carried state) is never indexed, so the union widening
    # ty sees on `states` does not apply.
    assets_pts = np.asarray(grids["assets"].to_jax())  # ty: ignore[unresolved-attribute]
    aime_pts = np.asarray(grids["aime"].to_jax())  # ty: ignore[unresolved-attribute]
    assets_lo, assets_hi = float(assets_pts.min()), float(assets_pts.max())
    aime_lo, aime_hi = float(aime_pts.min()), float(aime_pts.max())
    hcc_p_pts = np.asarray(grids["hcc_persistent"].to_jax())  # ty: ignore[unresolved-attribute]
    hcc_t_pts = np.asarray(grids["hcc_transitory"].to_jax())  # ty: ignore[unresolved-attribute]
    wage_res_pts = np.asarray(grids["log_ft_wage_res"].to_jax())  # ty: ignore[unresolved-attribute]

    # For lagged_labor_supply: 0 for tied rows (regime lacks the state),
    # random 0/1 for the others.
    tied_id = model.regime_names_to_ids["tied_nomc_inelig_canwork"]
    lls = np.where(regime == tied_id, 0, rng.integers(0, 2, size=n_subjects)).astype(
        np.int32
    )

    return {
        "regime_id": jnp.asarray(regime),
        "age": jnp.full(n_subjects, 51.0),
        "assets": jnp.asarray(rng.uniform(assets_lo, assets_hi, n_subjects)),
        "aime": jnp.asarray(rng.uniform(aime_lo, aime_hi, n_subjects)),
        # pension_wealth is a carried state seeded as the agent's true
        # pension wealth; the synthetic benchmark draws a modest positive stock.
        "pension_wealth": jnp.asarray(rng.uniform(0.0, 200_000.0, n_subjects)),
        "health": jnp.asarray(rng.integers(0, 3, n_subjects).astype(np.int32)),
        "hcc_persistent": jnp.asarray(rng.choice(hcc_p_pts, n_subjects)),
        "hcc_transitory": jnp.asarray(rng.choice(hcc_t_pts, n_subjects)),
        "spousal_income": jnp.asarray(rng.integers(0, 3, n_subjects).astype(np.int32)),
        "pref_type": jnp.asarray(
            rng.integers(0, _N_BENCHMARK_PREF_TYPES, n_subjects).astype(np.int32)
        ),
        "log_ft_wage_res": jnp.asarray(rng.choice(wage_res_pts, n_subjects)),
        "lagged_labor_supply": jnp.asarray(lls),
        # claimed_ss is required by non-initial regimes (ss="choose");
        # everyone starts as not-yet-claimed.
        "claimed_ss": jnp.zeros(n_subjects, dtype=jnp.int32),
    }
